def execute_sphene_cli_search(query: str):
    """Executes a search query against the 1,016 notes in vault_1k via Sphene CLI."""
    env = os.environ.copy()
    env["SPHENE_PORT"] = "8749"
    env["SPHENE_VAULT_DIR"] = VAULT_DIR
    env["SPHENE_DB_PATH"] = os.path.join(VAULT_DIR, ".sphene", "index.db")
    
    t0 = time.perf_counter()
    res = subprocess.run([SPHENE_BIN, "search", query], env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    latency_ms = (time.perf_counter() - t0) * 1000.0

    try:
        data = json.loads(res.stdout)
        if not data:
            return json.dumps({"results": [], "message": f"No matches found for '{query}'"}), latency_ms
        # Return top 3 results with snippets
        summarized = []
        for d in data[:3]:
            summarized.append({
                "path": d.get("path"),
                "title": d.get("title"),
                "snippet": d.get("snippet", "").replace("<b>", "").replace("</b>", "")[:180]
            })
        return json.dumps({"results": summarized, "count": len(data)}), latency_ms
    except Exception as e:
        return json.dumps({"error": str(e), "raw": res.stdout[:200]}), latency_ms

def execute_sphene_cli_read(path: str, section: str = None):
    """Reads a document or extracts a section heading."""
    clean_path = os.path.basename(path)
    abs_path = os.path.join(VAULT_DIR, clean_path)
    if not os.path.exists(abs_path):
        return json.dumps({"error": f"File '{clean_path}' not found in vault"}), 0.0

    t0 = time.perf_counter()
    with open(abs_path, "r", encoding="utf-8") as f:
        full_text = f.read()

    latency_ms = (time.perf_counter() - t0) * 1000.0

    if section:
        lines = full_text.splitlines()
        sec_lines = []
        capture = False
        sec_lower = section.lower()
        for line in lines:
            if line.startswith("#") and sec_lower in line.lower():
                capture = True
            elif capture and line.startswith("## ") and sec_lower not in line.lower():
                break
            if capture:
                sec_lines.append(line)
        if sec_lines:
            return "\n".join(sec_lines), latency_ms

    return full_text, latency_ms

def call_llm_agent(messages, tools=None):
    """Sends request to Qwen3.6-35B with tools enabled."""
    headers = {
        "Authorization": f"Bearer {LLM_API_KEY}",
        "Content-Type": "application/json"
    }
    payload = {
        "model": LLM_MODEL,
        "messages": messages,
        "max_tokens": 300,
        "temperature": 0.0
    }
    if tools:
        payload["tools"] = tools
        payload["tool_choice"] = "auto"

    t0 = time.perf_counter()
    r = requests.post(LLM_API_URL, headers=headers, json=payload, timeout=120)
    latency_sec = time.perf_counter() - t0

    if r.status_code != 200:
        raise RuntimeError(f"LLM API Error {r.status_code}: {r.text}")

    data = r.json()
    choice = data["choices"][0]["message"]
    usage = data.get("usage", {})

    return {
        "message": choice,
        "latency_sec": round(latency_sec, 2),
        "prompt_tokens": usage.get("prompt_tokens", 0),
        "completion_tokens": usage.get("completion_tokens", 0),
        "total_tokens": usage.get("total_tokens", 0)
    }

def run_autonomous_scenario(scenario_id, name, user_prompt, ground_truth_assert_fn, target_doc, target_info_desc):
    print("\n" + "=" * 90)
    print(f"  SCENARIO {scenario_id}: {name}")
    print(f"  Target Document:   {target_doc} (in vault with 1,016 total notes)")
    print(f"  Where Data Sits:   {target_info_desc}")
    print(f"  User Prompt:       \"{user_prompt}\" (NO file/section hints given)")
    print("=" * 90)

    system_prompt = (
        "You are an intelligent knowledge assistant connected to the user's Sphene second-brain vault.\n"
        "You have tools to search notes ('sphene_search') and read note contents ('sphene_read').\n"
        "When the user asks a question, use your tools to find the relevant note, read the required information, "
        "and provide a clear, accurate answer."
    )

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt}
    ]

    total_prompt_tokens = 0
    total_completion_tokens = 0
    tool_calls_log = []
    retrieved_data_log = []

    # Autonomous multi-turn loop
    for turn in range(1, 5):
        print(f"\n[Turn {turn}] Agent Thinking & Dispatching...")
        res = call_llm_agent(messages, tools=SPHENE_TOOLS)
        total_prompt_tokens += res["prompt_tokens"]
        total_completion_tokens += res["completion_tokens"]
        msg = res["message"]
        messages.append(msg)

        tool_calls = msg.get("tool_calls", [])
        if not tool_calls:
            print(f"  -> Agent produced final response directly.")
            final_content = msg.get("content", "").strip()
            break

        for tc in tool_calls:
            fn_name = tc["function"]["name"]
            fn_args = json.loads(tc["function"]["arguments"])
            print(f"  -> LLM Tool Call: {fn_name}({json.dumps(fn_args)})")
            tool_calls_log.append({"name": fn_name, "args": fn_args})

            if fn_name == "sphene_search":
                q = fn_args.get("query", "")
                tool_out, lat_ms = execute_sphene_cli_search(q)
                print(f"     [Sphene Search ({lat_ms:.1f}ms)]: Returned matches")
            elif fn_name == "sphene_read":
                p = fn_args.get("path", "")
                sec = fn_args.get("section")
                tool_out, lat_ms = execute_sphene_cli_read(p, sec)
                print(f"     [Sphene Read ({lat_ms:.1f}ms)]: Retrieved content for {p}")
            elif fn_name == "sphene_patch":
                tool_out = json.dumps({"status": "staged_for_human_review", "message": "AST Diff staged in Differential Timeline. Working copy on disk protected."})
                print(f"     [Sphene Patch]: Change staged in Differential Timeline")
            else:
                tool_out = json.dumps({"error": f"Unknown tool {fn_name}"})

            retrieved_data_log.append({"tool": fn_name, "args": fn_args, "snippet": tool_out[:200]})
            messages.append({
                "role": "tool",
                "tool_call_id": tc["id"],
                "content": tool_out
            })

    # Final verification
    final_answer = messages[-1].get("content", "")
    passed, reason = ground_truth_assert_fn(final_answer)

    print("\n--- Benchmark Execution Summary ---")
    print(f"  • Tools Invoked:       {[tc['name'] for tc in tool_calls_log]}")
    print(f"  • Total Turns:         {len(tool_calls_log) + 1}")
    print(f"  • Total Tokens:        {total_prompt_tokens + total_completion_tokens} (prompt: {total_prompt_tokens}, completion: {total_completion_tokens})")
    print(f"  • Final Answer:        {final_answer.strip()[:180]}...")
    print(f"  • Ground-Truth Match:  {'✓ PASSED' if passed else '✗ FAILED'} ({reason})")

    return {
        "scenario_id": scenario_id,
        "scenario_name": name,
        "vault_total_notes": 1016,
        "target_doc": target_doc,
        "target_location": target_info_desc,
        "user_prompt": user_prompt,
        "tool_calls": tool_calls_log,
        "retrieved_data_sample": retrieved_data_log,
        "final_answer": final_answer,
        "ground_truth_verified": passed,
        "verification_notes": reason,
        "tokens": {
            "prompt_tokens": total_prompt_tokens,
            "completion_tokens": total_completion_tokens,
            "total_tokens": total_prompt_tokens + total_completion_tokens
        }
    }

